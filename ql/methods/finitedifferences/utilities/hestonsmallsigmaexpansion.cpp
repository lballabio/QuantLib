#include <ql/methods/finitedifferences/utilities/hestonsmallsigmaexpansion.hpp>
#include <cmath>

namespace QuantLib {

namespace detail {

    // Generated by symbolic Taylor-series expansion (to O(sigma^2)) of the
    // exact single-segment Heston Riccati step
    //
    //   k    = kappa - i*rho*sigma*z
    //   d    = sqrt(k^2 + sigma^2*(z^2 + i*z))
    //   g    = (k-d)/(k+d)
    //   gt   = (k-d-Dprev*sigma^2)/(k+d-Dprev*sigma^2)
    //   Dnew = (k+d)/sigma^2 * (g-gt*exp(-d*tau))/(1-gt*exp(-d*tau))
    //   Cinc = kappa*theta/sigma^2 * ((k-d)*tau - 2*log((1-gt*exp(-d*tau))/(1-gt)))
    //
    // around sigma=0, generic in the terminal value Dprev (see the header
    // comment). Dprev=0 reproduces AnalyticHestonEngine::chF's existing
    // small-sigma branch to machine precision.
    void hestonSmallSigmaStep(
        Real kappa, Real theta, Real sigma, Real rho, Time tau,
        const std::complex<Real>& z, const std::complex<Real>& Dprev,
        std::complex<Real>& D, std::complex<Real>& C) {

        const std::complex<Real> i(0.0, 1.0);

        const std::complex<Real> t0 = kappa*kappa*kappa;
        const std::complex<Real> t1 = kappa*tau;
        const std::complex<Real> t2 = std::exp(t1);
        const std::complex<Real> t3 = Dprev*t0*t2;
        const std::complex<Real> t4 = kappa*kappa;
        const std::complex<Real> t5 = z + i;
        const std::complex<Real> t6 = t5*z;
        const std::complex<Real> t7 = t4*t6;
        const std::complex<Real> t8 = 0.5*t7;
        const std::complex<Real> t9 = 2.0*t1;
        const std::complex<Real> t10 = std::exp(t9);
        const std::complex<Real> t11 = i*z;
        const std::complex<Real> t12 = z*(t11 - 1.0);
        const std::complex<Real> t13 = i*Dprev;
        const std::complex<Real> t14 = 2.0*t13;
        const std::complex<Real> t15 = t14*t4*tau;
        const std::complex<Real> t16 = t12*t2;
        const std::complex<Real> t17 = kappa*t2;
        const std::complex<Real> t18 = rho*sigma*t17*z;
        const std::complex<Real> t19 = sigma*sigma;
        const std::complex<Real> t20 = 2.0*Dprev;
        const std::complex<Real> t21 = kappa*t20;
        const std::complex<Real> t22 = t21 + t6;
        const std::complex<Real> t23 = rho*rho;
        const std::complex<Real> t24 = tau*tau;
        const std::complex<Real> t25 = z*z;
        const std::complex<Real> t26 = 4.0*t23;
        const std::complex<Real> t27 = t26*z + t5;
        const std::complex<Real> t28 = t10*t25;
        const std::complex<Real> t29 = t2*(t21 - t27*z);
        const std::complex<Real> t30 = Dprev*z;
        const std::complex<Real> t31 = 2.0*t30;
        const std::complex<Real> t32 = t25*z;
        const std::complex<Real> t33 = t32*tau;
        const std::complex<Real> t34 = t23*t33;
        const std::complex<Real> t35 = t25*tau;
        const std::complex<Real> t36 = i*t35;
        const std::complex<Real> t37 = tau*z;
        const std::complex<Real> t38 = 2.0*t36;
        const std::complex<Real> t39 = -t33 - t38;
        const std::complex<Real> t40 = 2.0*z;
        const std::complex<Real> t41 = std::exp(-t9)/t0;
        const std::complex<Real> t42 = 8.0*t10;
        const std::complex<Real> t43 = i*t37;
        const std::complex<Real> t44 = t14 + t37;
        const std::complex<Real> t45 = Dprev*Dprev;
        const std::complex<Real> t46 = 4.0*t4;
        const std::complex<Real> t47 = t45*t46;
        const std::complex<Real> t48 = 2.0*t11 + t25 - 1.0;
        const std::complex<Real> t49 = t23*t25;
        const std::complex<Real> t50 = t11*t23;
        const std::complex<Real> t51 = 4.0*t25;
        const std::complex<Real> t52 = Dprev*t26;
        const std::complex<Real> t53 = t23*t24;

        D = t41*(-t10*t8 + 0.5*t18*(t1*t12 + t12 + t15 - t16)
            - 0.125*t19*(2.0*Dprev*kappa*t22 + 4.0*Dprev*t0*t2*t23*t24*t25
                - t17*t40*(t13 - t23*t38 + t26*t30 + t30 - 2.0*t34 + t37 + t39)
                - t2*t22*t6 + 2.0*t2*t4*tau*z*(t14 + t23*t36 + t31 + t34)
                - t21*t29 + t22*t5*z - t27*t28*t5 - t29*t6)
            + t2*t8 + t3);

        C = -0.0625*t41*theta*(t0*t42*(-t20 + t35 + t43)
            + 8.0*t18*(kappa*(t14 + t36 - t37) + 2.0*t12 + t15 - 2.0*t16
                - t17*(-t36 + t44))
            - t19*(4.0*Dprev*kappa*t6
                - kappa*t10*t40*(8.0*t23*t30 - t26*t33 - t26*t36 + t31 + t39 + t44)
                + t10*t47
                + t17*t51*(t26*t35 + t26*t43 + t35 + 2.0*t43 + t52 - tau)
                + t2*t46*(t14*t37 + t20*t35 + i*t32*t53 + t35*t52 - 2.0*t45
                    + t53*t25*t25)
                + t2*t51*(t48 + 6.0*t49 + 6.0*t50)
                + 8.0*t24*t3*t49 + t25*t48
                - t28*(10.0*t11 + 5.0*t25 + 24.0*t49 + 24.0*t50 - 5.0) + t47)
            + 8.0*t2*t7 + 16.0*t3 - t42*t7);
    }

}

}
